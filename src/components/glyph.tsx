export type GlyphName = keyof typeof GLYPHS;

export function Glyph({ name, size = 22, color }: {
  name: GlyphName | string;
  size?: number;
  color: string;
  /** Retained for existing callers; filled glyphs have no outline stroke. */
  strokeWidth?: number;
}) {
  const Drawn = GLYPHS[name] ?? IconSparklesFilled;
  return <Drawn testID={`filled-glyph-${name}`} color={color} fill={color} size={size} strokeWidth={0} />;
}
